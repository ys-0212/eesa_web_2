// Generates src/svgs.ts from the inline SVGs captured in analysis/raw/svg-by-id/ (original artwork),
// stripping Astro scoping attributes and analytics hooks. Logo names/heights come from the captured
// logo-river markup (analysis/raw/sections/03.html).
// Usage: node scripts/media/svg-extract.mjs
import fs from 'node:fs';

const dir = 'analysis/raw/svg-by-id';
const read = (id) => fs.readFileSync(`${dir}/svg${String(id).padStart(3, '0')}.svg`, 'utf8');
const clean = (s) => s
  .replace(/\s+data-astro-cid-[\w-]+="[^"]*"/g, '')
  .replace(/\s+data-astro-source-[\w-]+="[^"]*"/g, '')
  .replace(/<!--[\s\S]*?-->/g, '')
  .replace(/<\?xml[^>]*\?>/g, '')
  // Illustrator class styles (.st0{fill:currentColor}) -> inline attribute so no <style> is needed.
  .replace(/<style[^>]*>\s*\.st0\{fill:currentColor;\}\s*<\/style>/g, '')
  .replace(/class="st0"/g, 'fill="currentColor"')
  .replace(/xmlns="https:\/\/www\.w3\.org\/2000\/svg"/g, 'xmlns="http://www.w3.org/2000/svg"')
  .replace(/\s{2,}/g, ' ')
  .replace(/>\s+</g, '><')
  .trim();

const named = {
  sentryLogo: 0,
  chevronRight: 1,
  botIcon: 21,
  carouselPrev: 66,
  carouselNext: 67,
  copyIcon: 68,
  badgeGdpr: 109,
  badgeSoc2: 110,
  badgeIso27001: 111,
  badgeHipaa: 112,
  footerWave: 113,
  footerSentryMark: 114,
  openSourcePledge: 115,
};

const logoHtml = fs.readFileSync('analysis/raw/sections/03.html', 'utf8');
const logos = [];
const re = /data-logo-name="([^"]+)"[^>]*data-overflow="false"[\s\S]*?--logo-max-height: ([\d.]+rem)[\s\S]*?svg-ref id="svg(\d+)"/g;
let m;
while ((m = re.exec(logoHtml))) logos.push({ name: m[1], maxHeight: m[2], svg: clean(read(Number(m[3]))) });

let out = '// Generated by scripts/media/svg-extract.mjs from the reference page\'s inline SVG artwork.\n';
out += '// Do not edit by hand: replace the source SVGs or edit content references in src/content.ts.\n\n';
out += 'export const svgs = {\n';
for (const [k, id] of Object.entries(named)) out += `  ${k}: ${JSON.stringify(clean(read(id)))},\n`;
out += '} as const;\n\nexport type SvgName = keyof typeof svgs;\n\n';
out += 'export const customerLogoSvgs: { name: string; maxHeight: string; svg: string }[] = ' + JSON.stringify(logos, null, 1) + ';\n';
fs.writeFileSync('src/svgs.ts', out);
console.log('named', Object.keys(named).length, 'logos', logos.length, logos.map((l) => `${l.name}:${l.maxHeight}`).join(' '));
