// Generates src/snippets.ts (Getting Started platforms + Shiki-coloured code tokens) from
// analysis/measurements/snippets.json. Usage: node scripts/media/snippets-extract.mjs
import fs from 'node:fs';
const d = JSON.parse(fs.readFileSync('analysis/measurements/snippets.json', 'utf8'));
const byId = Object.fromEntries(d.snippets.map((s) => [s.id, s]));
const platforms = d.options.map((o) => {
  const s = byId[o.value];
  return {
    value: o.value,
    label: o.label,
    docsUrl: s?.docsUrl ?? 'https://docs.sentry.io/platforms/',
    blocks: (s?.blocks ?? []).map((b) => b.type === 'code'
      ? { type: 'code', lang: b.lang, lines: b.lines.map((l) => l.map((t) => (t.color ? [t.text, t.color] : [t.text]))) }
      : { type: 'html', tag: b.tag, html: b.html.replace(/\s*data-astro-cid-[\w-]+="[^"]*"/g, '').replace(/\s+/g, ' ') }),
  };
});
let out = '// Generated by scripts/media/snippets-extract.mjs from the reference Getting Started section.\n';
out += '// Each code line is a list of [text, colour?] tokens (Shiki github-dark palette).\n\n';
out += 'export type SnippetToken = [string] | [string, string];\n';
out += 'export type SnippetBlock =\n  | { type: "code"; lang?: string; lines: SnippetToken[][] }\n  | { type: "html"; tag: string; html: string };\n';
out += 'export type Platform = { value: string; label: string; docsUrl: string; blocks: SnippetBlock[] };\n\n';
out += `export const platforms: Platform[] = ${JSON.stringify(platforms, null, 1)};\n`;
fs.writeFileSync('src/snippets.ts', out);
console.log('platforms', platforms.length, 'blocks', platforms.reduce((n, p) => n + p.blocks.length, 0));
console.log([...new Set(platforms.flatMap((p) => p.blocks.filter((b) => b.type === 'html').map((b) => b.tag)))]);
